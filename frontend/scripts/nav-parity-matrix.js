#!/usr/bin/env node
/*
 * Prints the navigation parity matrix (markdown) straight from the navigation
 * registry, so the document can never drift from the code that decides visibility.
 * Usage: node scripts/nav-parity-matrix.js > ../docs/PHASE1_NAV_PARITY_MATRIX.md
 */
const fs = require('fs');
const path = require('path');
const ts = require('typescript');

require.extensions['.ts'] = (module, filename) => {
  const out = ts.transpileModule(fs.readFileSync(filename, 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2019, experimentalDecorators: true },
  });
  module._compile(out.outputText, filename);
};

// The language service only needs the @Injectable decorator; avoid loading the Angular runtime.
const Module = require('module');
const load = Module._load;
Module._load = function (request, ...rest) {
  if (request === '@angular/core') return { Injectable: () => () => undefined };
  return load.call(this, request, ...rest);
};

const app = path.join(__dirname, '..', 'src', 'app');
const { NAV_GROUPS, NAV_EXTRA_TITLES } = require(path.join(app, 'layout', 'navigation', 'nav.registry.ts'));
global.localStorage = { getItem: () => null, setItem: () => undefined };
const { BmsLanguageService } = require(path.join(app, 'components', 'bms', 'bms-language.service.ts'));
const language = new BmsLanguageService();
const label = key => language.t(key);
const cell = text => String(text).replace(/\|/g, '\\|');

const lines = [];
lines.push('# Phase 1 — navigation permission parity matrix', '');
lines.push('Generated by `frontend/scripts/nav-parity-matrix.js` from `frontend/src/app/layout/navigation/nav.registry.ts`.', '');
lines.push('**Legacy links.** The rule column is the effective condition of the retired `navbar.component.html` (group header `&&` container `&&` link, loose `==`). The unified sidebar evaluates the same expression, so old rule = new rule. `OR` joins the blocks of a route the old navbar listed more than once.', '');
lines.push('**BMS links.** The retired BMS sidebar showed a link only with the listed ability; the unified sidebar keeps that rule. The retired top navbar additionally listed the same 16 `/bms` routes without any check (the pages were still guarded by `BmsPermissionGuard`); those ungated duplicates are not carried over. This is the only intentional difference, and it only removes links to pages the user could not open.', '');
lines.push('A group is rendered only when at least one of its links is visible. Evidence: `nav.registry.spec.ts` compares the registry with an independent port of the old template for every combination of 6 departments, 4 positions, 4 roles, 32 module sets and 33 permission sets.', '');
let total = 0;
for (const section of ['bms', 'workspace']) {
  lines.push(section === 'bms' ? '## Business Management (BMS)' : '## Legacy workspaces', '');
  for (const group of NAV_GROUPS.filter(g => g.section === section)) {
    lines.push(`### ${label(group.label)} (\`${group.id}\`)${group.badge ? ` — group badge \`${group.badge}\`` : ''}`, '');
    lines.push('| Link | Route | Visibility rule | Badge |', '|---|---|---|---|');
    for (const item of group.items) {
      total++;
      lines.push(`| ${cell(label(item.label))} | \`${item.route}\` | \`${cell(item.source)}\` | ${item.badge ? '`' + item.badge + '`' : '—'} |`);
    }
    lines.push('');
  }
}
lines.push(`Total sidebar links: **${total}** in **${NAV_GROUPS.length}** groups.`, '');
lines.push('## Pages with a header title but no sidebar link', '', '| Route prefix | Title |', '|---|---|');
for (const extra of NAV_EXTRA_TITLES) lines.push(`| \`${extra.prefix}\` | ${cell(label(extra.label))} |`);
lines.push('');
process.stdout.write(lines.join('\n'));
